import 'dart:async';
import 'dart:convert';
import 'dart:typed_data';

import 'package:shellx_core/shellx_core.dart';

import '../pairing/pairing_id.dart';

/// A phone this agent trusts (spec §5.3 step 5).
final class TrustedDevice {
  /// Throws [ArgumentError] unless [pairingId] is a lower-case UUIDv7.
  TrustedDevice({
    required this.mobileId,
    required Uint8List publicKey,
    required this.name,
    required this.pairedAt,
    required this.pairingId,
  }) : publicKey = Uint8List.fromList(publicKey) {
    if (!isPairingId(pairingId)) {
      throw ArgumentError.value(
        pairingId,
        'pairingId',
        'must be a lower-case UUIDv7',
      );
    }
  }

  final String mobileId;
  final Uint8List publicKey;
  final String name;
  final DateTime pairedAt;

  /// Id of the pairing that created this entry (UUIDv7 generated by the
  /// agent at `pair.confirm`). `pairing_removed` events, the relay's `410`
  /// and the agent's revoke are matched by it (overview §4.3).
  final String pairingId;

  Map<String, Object?> toJson() => {
    'mobile_id': mobileId,
    'public_key': base64UrlNoPad(publicKey),
    'name': name,
    'paired_at': pairedAt.millisecondsSinceEpoch,
    'pairing_id': pairingId,
  };

  /// Throws [FormatException] for a malformed entry (including a public key
  /// that is not 32 bytes or a missing or invalid pairing id).
  static TrustedDevice fromJson(Map<String, Object?> json) {
    final publicKey = fromBase64UrlNoPad(json['public_key'] as String);
    if (publicKey.length != 32) {
      throw FormatException('Public key must be exactly 32 bytes');
    }
    final pairingId = json['pairing_id'];
    if (pairingId is! String || !isPairingId(pairingId)) {
      throw const FormatException('Missing or invalid pairing id');
    }
    return TrustedDevice(
      mobileId: json['mobile_id'] as String,
      publicKey: publicKey,
      name: json['name'] as String,
      pairedAt: DateTime.fromMillisecondsSinceEpoch(
        json['paired_at'] as int,
        isUtc: true,
      ),
      pairingId: pairingId,
    );
  }
}

/// A stored trust entry: the device plus whether the relay has yet to
/// acknowledge its pairing (`POST /v1/pairings`).
final class _Entry {
  const _Entry(this.device, {this.unregistered = false});
  final TrustedDevice device;
  final bool unregistered;

  Map<String, Object?> toJson() => {
    ...device.toJson(),
    if (unregistered) 'unregistered': true,
  };
}

/// Local trust list — the only source of truth for trust (spec §5.4).
/// Stored as a JSON array under [storageKey]. Unreadable data counts as
/// "no trusted devices" (fail closed); so does an entry without a valid
/// pairing id.
///
/// An entry can be marked "unregistered": its pairing has not been
/// acknowledged by the relay yet (`POST /v1/pairings` with its pairing id is
/// still to be sent or retried). The mark is stored in the entry itself, so
/// it belongs to exactly that pairing and goes away with it.
///
/// **Important:** Create one shared instance per underlying [KeyValueStore]
/// instance. The mutation lock is per [TrustedStore] instance.
final class TrustedStore {
  TrustedStore(KeyValueStore store) : _store = store;

  static const String storageKey = 'trusted_devices';

  final KeyValueStore _store;
  final _changes = StreamController<void>.broadcast();
  Future<void> _lock = Future.value();

  /// Fires whenever the list of trusted devices changes (not when only an
  /// unregistered mark is cleared).
  Stream<void> get changes => _changes.stream;

  Future<List<TrustedDevice>> list() async => [
    for (final entry in await _read()) entry.device,
  ];

  Future<TrustedDevice?> find(String mobileId) async =>
      _entryOf(await _read(), mobileId)?.device;

  /// Adds [device], replacing an entry with the same mobileId (and that
  /// entry's mark). With [unregistered], the new entry is marked.
  Future<void> add(TrustedDevice device, {bool unregistered = false}) =>
      _locked(() async {
        final entries = await _read();
        await _write([
          ...entries.where((e) => e.device.mobileId != device.mobileId),
          _Entry(device, unregistered: unregistered),
        ]);
        _changes.add(null);
      });

  /// Removes [mobileId]'s entry — with [pairingId], only if the entry still
  /// belongs to that pairing. Returns whether an entry was removed; nothing
  /// is written otherwise (the relay replays `pairing_removed`).
  Future<bool> remove(String mobileId, {String? pairingId}) =>
      _locked(() async {
        final entries = await _read();
        final entry = _entryOf(entries, mobileId);
        if (entry == null ||
            (pairingId != null && entry.device.pairingId != pairingId)) {
          return false;
        }
        await _write([
          for (final e in entries)
            if (!identical(e, entry)) e,
        ]);
        _changes.add(null);
        return true;
      });

  Future<void> clear() => _locked(() async {
    await _write(const []);
    _changes.add(null);
  });

  /// Trusted devices whose pairing the relay has not acknowledged yet.
  Future<List<TrustedDevice>> unregistered() async => [
    for (final entry in await _read())
      if (entry.unregistered) entry.device,
  ];

  /// The relay acknowledged (or refused for good) pairing [pairingId] of
  /// [mobileId]: clears the entry's mark. Returns whether [mobileId]'s entry
  /// still belongs to that pairing; a replaced or removed pairing is left
  /// alone.
  Future<bool> markRegistered(String mobileId, String pairingId) =>
      _locked(() async {
        final entries = await _read();
        final entry = _entryOf(entries, mobileId);
        if (entry == null || entry.device.pairingId != pairingId) return false;
        if (entry.unregistered) {
          await _write([
            for (final e in entries) identical(e, entry) ? _Entry(e.device) : e,
          ]);
        }
        return true;
      });

  static _Entry? _entryOf(List<_Entry> entries, String mobileId) {
    for (final entry in entries) {
      if (entry.device.mobileId == mobileId) return entry;
    }
    return null;
  }

  Future<List<_Entry>> _read() async {
    final raw = await _store.read(storageKey);
    if (raw == null || raw.isEmpty) return [];
    try {
      final decoded = jsonDecode(raw) as List<Object?>;
      final entries = <_Entry>[];
      for (final item in decoded) {
        try {
          final json = (item as Map).cast<String, Object?>();
          entries.add(
            _Entry(
              TrustedDevice.fromJson(json),
              unregistered: json['unregistered'] == true,
            ),
          );
        } catch (_) {
          // Skip corrupt entries (e.g., wrong key length, no pairing id).
        }
      }
      return entries;
    } catch (_) {
      return [];
    }
  }

  Future<void> _write(List<_Entry> entries) => _store.write(
    storageKey,
    jsonEncode([for (final e in entries) e.toJson()]),
  );

  /// Runs [body] after every earlier mutation; a failure does not block the
  /// next one.
  Future<T> _locked<T>(Future<T> Function() body) {
    final next = _lock.then((_) => body());
    _lock = next.then<void>((_) {}, onError: (Object _) {});
    return next;
  }
}
