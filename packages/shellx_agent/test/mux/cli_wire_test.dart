import 'dart:io';
import 'dart:typed_data';

import 'package:shellx_agent/shellx_agent.dart';
import 'package:shellx_core/shellx_core.dart';
import 'package:test/test.dart';

/// Shared with `term/` (Rust reads the same file, A7 D37b).
final _vectorsFile = File('../../term/protocol/mux_vectors.txt');

final _secret = Uint8List.fromList(List.filled(32, 0x42));
final _nonceClient = Uint8List.fromList(List.generate(32, (i) => i + 1));
final _nonceDaemon = Uint8List.fromList(List.generate(32, (i) => 0x80 + i));

/// A7 amendment: a fixed per-launch token (64 hex, like the real one).
const _token =
    '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef';

/// name → CBOR bytes of the payload (no length prefix), keys in the
/// insertion order written here (Dart maps keep it).
Map<String, Uint8List> _samples() => {
  'cli.hello': encodeCbor({
    't': 'hello',
    'protocol': 1,
    'app': 'shellx-cli/0.1.0',
    'role': 'cli',
    'nonce': _nonceClient,
  }),
  'cli.auth': encodeCbor({
    't': 'auth',
    'proof': clientProof(_secret, _nonceDaemon, _nonceClient),
  }),
  'cli.auth_token': encodeCbor({
    't': 'auth',
    'proof': clientProof(_secret, _nonceDaemon, _nonceClient),
    'token': _token,
  }),
  'cli.api_version': encodeCbor({'t': 'api.version', 'q': 1}),
  'host.api_version': encodeCbor({
    't': 'result',
    'q': 1,
    'api': 1,
    'app': '1.7.0',
    'host': 'ui',
    'ui': true,
    'caps': ['ui.ls', 'ui.browser'],
  }),
  'host.error': encodeCbor({
    't': 'error',
    'q': 2,
    'code': 'not_found',
    'message': 'no pane p12',
  }),
  'host.event': encodeCbor({
    't': 'event',
    'kind': 'pane.exited',
    'pane': 12,
    'tab': -3,
    'exitCode': null,
  }),
};

String _hex(Uint8List b) =>
    b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();

void main() {
  test('cli role allowlist (A7 D3)', () {
    for (final t in [
      'api.version',
      'cli.notify',
      'ui.ls',
      'ui.browser.eval',
      'daemon.status',
    ]) {
      expect(CliType.allowedForCli(t), isTrue, reason: t);
    }
    for (final t in [
      'sessions.open',
      'view.write',
      'agent.call',
      'daemon.quit',
      'hello',
      'uix',
    ]) {
      expect(CliType.allowedForCli(t), isFalse, reason: t);
    }
  });

  test('result and error helpers', () {
    expect(cliResult(3, {'pane': 9}).fields, {'pane': 9});
    expect(cliResult(3).type, MuxType.result);
    final e = cliErrorMessage(4, CliError.cliDisabled, 'off');
    expect(
      [e.type, e.q, e.get<String>('code'), e.get<String>('message')],
      [MuxType.error, 4, 'cli_disabled', 'off'],
    );
  });

  test('caps: what this host serves; no ui.browser while A6 is absent', () {
    expect(kCliApi, 1);
    expect(kCliCaps, isNot(contains('ui.browser')));
    expect(kCliCaps, contains('ui.config')); // A9 D39
    expect(
      kCliCaps,
      containsAll([CliType.cliNotify, CliType.uiLs, CliType.uiPaneRead]),
    );
    expect(kCliCaps.every(CliType.allowedForCli), isTrue);
  });

  test('A8: ssh and tmux types, caps and error codes', () {
    expect(
      [CliType.uiSshOpen, CliType.uiTmuxList, CliType.uiTmuxAttach],
      ['ui.ssh.open', 'ui.tmux.list', 'ui.tmux.attach'],
    );
    expect(kCliCaps, containsAll(['ui.ssh', 'ui.tmux']));
    expect(
      [CliError.sshUnavailable, CliError.tmuxUnavailable, CliError.tmuxFailed],
      ['ssh_unavailable', 'tmux_unavailable', 'tmux_failed'],
    );
    for (final t in [
      CliType.uiSshOpen,
      CliType.uiTmuxList,
      CliType.uiTmuxAttach,
    ]) {
      expect(CliType.allowedForCli(t), isTrue, reason: t);
    }
  });

  test('golden vectors match term/protocol/mux_vectors.txt', () {
    final lines = {
      for (final l in _vectorsFile.readAsLinesSync())
        if (l.isNotEmpty && !l.startsWith('#'))
          l.split('=')[0]: l.split('=')[1],
    };
    final samples = _samples();
    final expected = {
      'auth.secret': _hex(_secret),
      'auth.nonce_client': _hex(_nonceClient),
      'auth.nonce_daemon': _hex(_nonceDaemon),
      'auth.daemon_proof': _hex(
        daemonProof(_secret, _nonceClient, _nonceDaemon),
      ),
      'auth.client_proof': _hex(
        clientProof(_secret, _nonceDaemon, _nonceClient),
      ),
      for (final e in samples.entries) e.key: _hex(e.value),
    };
    if (Platform.environment['WRITE_VECTORS'] == '1') {
      _vectorsFile.writeAsStringSync(
        [
          '# A5b mux / A7 CLI reference bytes. name=hex of the CBOR map (no length prefix).',
          '# Generated by packages/shellx_agent/test/mux/cli_wire_test.dart (WRITE_VECTORS=1);',
          '# read by term/src/api tests. Never edit by hand.',
          for (final e in expected.entries) '${e.key}=${e.value}',
          '',
        ].join('\n'),
      );
    }
    expect(lines, expected);
  });
}
