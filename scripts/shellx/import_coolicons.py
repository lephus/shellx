#!/usr/bin/env python3
"""Build the ShellX coolicons asset catalog from the coolicons v4.1 release.

Usage:
    python3 scripts/shellx/import_coolicons.py <coolicons.v4.1.zip> [--out DIR]

Each of the 442 coolicons (24x24, 2 px round strokes) is turned into an SF
Symbols custom-symbol template (``<Name>.symbolset``) so that SwiftUI
``Image(_:bundle:)`` and AppKit ``NSImage(symbolName:bundle:variableValue:)``
treat it like an SF Symbol: it scales with ``.font``/``.imageScale`` and
``NSImage.SymbolConfiguration(pointSize:)`` and renders as a template.
The license notice (``NOTICE``) is written next to the catalog. One extra
symbol is derived from a coolicon (``DERIVED``): ``Circle_Fill``, the
``Circle`` outline filled in, for the status dots the app draws (coolicons
has no solid circle).

Custom symbols must be filled outlines, so the strokes are expanded to fills
with skia-pathops (via picosvg). That is a dev-time dependency only; install
the pinned versions into a throwaway venv outside the repo:

    python3 -m venv "$TMPDIR/coolicons-venv"
    "$TMPDIR/coolicons-venv/bin/pip" install picosvg==0.22.3 skia-pathops==0.8.0.post2 numpy
    "$TMPDIR/coolicons-venv/bin/python" scripts/shellx/import_coolicons.py coolicons.v4.1.zip --verify

``--verify`` (numpy) checks every outline against the exact stroke region
before anything is written. The output is byte-identical for the pinned
release zip and tool versions: icons are processed in sorted order and
coordinates are rounded. Other skia-pathops builds move a few curve points by
a thousandth of a unit, which is why the versions are pinned (and checked).

Release: https://github.com/krystonschwarze/coolicons/releases/download/v4.1/coolicons.v4.1.zip
sha256:  5311b1b44e345b19007902db55418c3a0b35fac825a38fbb9038bbf3a077e11c
License: CC BY 4.0, "coolicons by Kryston Schwarze" (see NOTICE next to the catalog).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "Packages/Shared/ShellXBrand/Sources/ShellXIcons/Resources/Coolicons.xcassets"
SVG_DIR = "cooliocns SVG"  # sic: the folder name inside the v4.1 zip
RELEASE_SHA256 = "5311b1b44e345b19007902db55418c3a0b35fac825a38fbb9038bbf3a077e11c"
ICON_COUNT = 442
PINNED_TOOLS = {"picosvg": "0.22.3", "skia-pathops": "0.8.0.post2"}
NOTICE = """\
coolicons v4.1 by Kryston Schwarze
https://github.com/krystonschwarze/coolicons

Licensed under the Creative Commons Attribution 4.0 International License
(CC BY 4.0): https://creativecommons.org/licenses/by/4.0/

Credit: "coolicons by Kryston Schwarze" (shown in ShellX's About window).

Changes: the 442 SVGs of the v4.1 release were converted to SF Symbols
custom-symbol templates (Coolicons.xcassets/<Name>.symbolset). The 2 px
strokes were expanded to filled outlines and the glyphs were scaled and
positioned on the symbol template's Small/Medium/Large guides. The drawings
are otherwise unchanged, except for one derived symbol: Circle_Fill is the
Circle icon with its inside filled (a solid status dot). Generated by
scripts/shellx/import_coolicons.py.
"""
# Symbols derived from a coolicon: {name: (source coolicon, transformation)}.
# "filled" keeps only the outline's outermost contour, i.e. fills the shape.
DERIVED = {"Circle_Fill": ("Circle", "filled")}

# Symbol template geometry (SF Symbols template v3, point size 100).
BASELINE = {"S": 696.0, "M": 1126.0, "L": 1556.0}
CAP_HEIGHT = 70.459
# 1 coolicon unit -> 5 symbol units at the M scale. Calibrated against SF
# Symbols at 100 pt Regular: SF `circle` draws a ~100-unit ring, the
# coolicons Circle ring is 20 units (radius 9 + 1 stroke) -> 100. A 2 px
# stroke becomes 10 units (SF Regular is ~8.6, Medium ~10).
SCALE = 5.0
# SF Symbols' small/large image scales relative to medium (measured: SF
# `terminal` at 13 pt is 14/19/24 pt wide for S/M/L).
SCALE_RATIO = {"S": 0.783, "M": 1.0, "L": 1.29}
# Side bearing either side of the glyph's ink, in symbol units at M (SF
# `circle` at 100 pt: 117 wide for a ~100-unit ring).
SIDE_BEARING = 8.5
LEFT_MARGIN_X = 1400.0
PICOSVG_HINT = (
    "picosvg is required (dev-time only): python3 -m venv \"$TMPDIR/coolicons-venv\" && "
    "\"$TMPDIR/coolicons-venv/bin/pip\" install "
    + " ".join(f"{name}=={version}" for name, version in PINNED_TOOLS.items())
)


def _picosvg():
    try:
        from picosvg.svg import SVG  # type: ignore
        from picosvg.svg_transform import Affine2D  # type: ignore
    except ImportError:  # pragma: no cover - dev-time tool
        sys.exit(PICOSVG_HINT)
    return SVG, Affine2D


def check_tool_versions() -> None:
    """Refuse to run with other picosvg/skia-pathops versions: their output
    differs in the last rounded digit, so the catalog would not reproduce."""
    from importlib import metadata

    for name, pinned in PINNED_TOOLS.items():
        try:
            found = metadata.version(name)
        except metadata.PackageNotFoundError:
            sys.exit(PICOSVG_HINT)
        if found != pinned:
            sys.exit(f"{name} {found} is installed; the catalog is pinned to {pinned}. {PICOSVG_HINT}")


def load_svgs(source: Path) -> dict[str, bytes]:
    """Return {CooliconName: svg bytes} from the pinned v4.1 release zip."""
    if not source.is_file():
        sys.exit(f"{source}: expected the coolicons v4.1 release zip")
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != RELEASE_SHA256:
        sys.exit(f"{source}: sha256 {digest} is not the coolicons v4.1 release ({RELEASE_SHA256})")
    out: dict[str, bytes] = {}
    with zipfile.ZipFile(source) as zf:
        for info in zf.infolist():
            name = info.filename
            # The release ships the same icons several times (SVG folder,
            # PNG, IconJar, sprite, webfont); only the categorised SVG folder
            # `<SVG_DIR>/<Category>/<Name>.svg` is used.
            parts = name.split("/")
            if len(parts) != 3 or parts[0] != SVG_DIR or not name.endswith(".svg"):
                continue
            stem = Path(name).stem
            if stem in out:
                sys.exit(f"duplicate coolicon name: {stem}")
            out[stem] = zf.read(info)
    bad = sorted(n for n in out if not re.fullmatch(r"[A-Za-z0-9_]+", n))
    if bad:
        sys.exit(f"unexpected coolicon names: {bad}")
    if len(out) != ICON_COUNT:
        sys.exit(f"expected {ICON_COUNT} coolicons in the v4.1 release, found {len(out)}")
    return dict(sorted(out.items()))


def centerlines(svg_bytes: bytes):
    """The icon's stroked paths as skia paths (coolicon units). Every v4.1
    coolicon is 2 px round-capped, round-joined strokes and no fills; any
    other input is refused rather than outlined wrongly."""
    SVG, _ = _picosvg()
    from picosvg.svg_pathops import skia_path  # type: ignore

    out = []
    for shape in SVG.fromstring(svg_bytes.decode("utf-8")).shapes():
        style = (shape.fill, shape.stroke_width, shape.stroke_linecap, shape.stroke_linejoin)
        if style != ("none", 2.0, "round", "round") or shape.stroke in ("none", None) or shape.transform:
            raise ValueError(f"unsupported coolicon shape {style} stroke={shape.stroke} transform={shape.transform}")
        out.append(skia_path(shape.as_path().as_cmd_seq(), "nonzero"))
    if not out:
        raise ValueError("icon has no stroked shapes")
    return out


# Skia's stroker approximates curve offsets to about a quarter of a unit, i.e.
# a quarter pixel when units are pixels. A coolicon is only 24 units wide, so
# stroke it 16x larger and scale back: the outline then follows the exact
# stroke region to well under 0.15 units (checked by --verify).
STROKE_UPSCALE = 16.0


def outline_path(svg_bytes: bytes):
    """Expand the strokes to filled outlines; return them as one picosvg
    path in coolicon units.

    Each subpath is stroked and simplified on its own, and the pieces are
    concatenated without a boolean union: the symbol is filled with the
    nonzero rule and every simplified piece winds the same way, so overlaps
    stay filled. (picosvg's topicosvg() strokes the whole icon and then
    unions the overlapping pieces; skia's union drops pieces that meet at
    nearly coincident points, e.g. the folded corner of File_Blank and the
    meridians of Globe.)"""
    _picosvg()
    import pathops  # type: ignore
    from picosvg.svg_pathops import svg_commands  # type: ignore
    from picosvg.svg_types import SVGPath  # type: ignore

    up = STROKE_UPSCALE
    result = pathops.Path()
    for centre in centerlines(svg_bytes):
        for contour in centre.contours:
            piece = pathops.Path()
            contour.draw(piece.getPen())
            piece = piece.transform(up, 0, 0, up, 0, 0)
            piece.stroke(2.0 * up, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4.0)
            piece.convertConicsToQuads(0.01 * up)
            piece.simplify(fix_winding=True)
            result.addPath(piece.transform(1 / up, 0, 0, 1 / up, 0, 0))
    return [SVGPath.from_commands(svg_commands(result))]


def derived_path(source_svg: bytes, transformation: str):
    """A symbol derived from a coolicon's outline (see ``DERIVED``)."""
    if transformation != "filled":
        raise ValueError(f"unknown derivation {transformation}")
    import pathops  # type: ignore
    from picosvg.svg_pathops import skia_path, svg_commands  # type: ignore
    from picosvg.svg_types import SVGPath  # type: ignore

    outline = skia_path(outline_path(source_svg)[0].as_cmd_seq(), "nonzero")
    outer = max(outline.contours, key=lambda contour: abs(contour.area))
    filled = pathops.Path()
    outer.draw(filled.getPen())
    return [SVGPath.from_commands(svg_commands(filled))]


def verify_outlines(icons: dict[str, bytes], step: float = 0.125, band: float = 0.15) -> list[str]:
    """Compare each outline with its exact stroke region and return the
    icons that differ. With round caps and joins, a 2-unit stroke covers
    exactly the points within 1 unit of the centreline; sample a grid over
    the 24x24 frame (ignoring a +-``band`` strip along the edge, where both
    sides are approximations) and compare that with the outline's nonzero
    fill. Needs numpy (dev-time only)."""
    try:
        import numpy as np  # type: ignore
    except ImportError:  # pragma: no cover - dev-time tool
        sys.exit("--verify needs numpy in the same venv: pip install numpy")
    from picosvg.svg_pathops import svg_commands  # type: ignore

    grid = np.arange(step / 2, 24, step)
    px, py = np.meshgrid(grid, grid)
    pts = np.stack([px.ravel(), py.ravel()], axis=1)

    def polylines(cmds, n=24):
        polys, cur, start = [], [], None
        ts = np.linspace(0, 1, n + 1)[1:]
        for cmd, args in cmds:
            if cmd == "M":
                if len(cur) > 1:
                    polys.append(np.array(cur))
                cur, start = [args[0:2]], args[0:2]
            elif cmd == "L":
                cur.append(args[0:2])
            elif cmd == "Q":
                p0, c, e = np.array(cur[-1]), np.array(args[0:2]), np.array(args[2:4])
                cur += [tuple((1 - t) ** 2 * p0 + 2 * (1 - t) * t * c + t * t * e) for t in ts]
            elif cmd == "C":
                p0, c1, c2, e = (np.array(cur[-1]), np.array(args[0:2]), np.array(args[2:4]), np.array(args[4:6]))
                cur += [tuple((1 - t) ** 3 * p0 + 3 * (1 - t) ** 2 * t * c1 + 3 * (1 - t) * t * t * c2 + t ** 3 * e)
                        for t in ts]
            elif cmd == "Z":
                if start is not None:
                    cur.append(start)
                if len(cur) > 1:
                    polys.append(np.array(cur))
                cur = []
            else:
                raise ValueError(f"unexpected path command {cmd}")
        if len(cur) > 1:
            polys.append(np.array(cur))
        return np.concatenate([p[:-1] for p in polys]), np.concatenate([p[1:] for p in polys])

    def distance(a, b):
        d = b - a
        dd = np.where((d * d).sum(-1) == 0, 1, (d * d).sum(-1))
        best = np.full(len(pts), np.inf)
        for chunk in range(0, len(pts), 512):
            p = pts[chunk:chunk + 512]
            ap = p[:, None, :] - a[None]
            t = np.clip((ap * d[None]).sum(-1) / dd[None], 0, 1)
            proj = a[None] + t[..., None] * d[None]
            best[chunk:chunk + 512] = np.sqrt(((p[:, None, :] - proj) ** 2).sum(-1)).min(1)
        return best

    def filled(a, b):
        """Nonzero winding of every sample, one scanline (grid row) at a time:
        sum the directions of the edges crossing the row right of the sample."""
        inside = np.zeros((len(grid), len(grid)), dtype=bool)
        for row, y in enumerate(grid):
            rising = (a[:, 1] <= y) & (b[:, 1] > y)
            falling = (a[:, 1] > y) & (b[:, 1] <= y)
            crossing = rising | falling
            ea, eb = a[crossing], b[crossing]
            xs = ea[:, 0] + (y - ea[:, 1]) * (eb[:, 0] - ea[:, 0]) / (eb[:, 1] - ea[:, 1])
            direction = np.where(rising[crossing], 1, -1)
            order = np.argsort(xs)
            xs, direction = xs[order], direction[order]
            right_sum = np.concatenate([np.cumsum(direction[::-1])[::-1], [0]])
            inside[row] = right_sum[np.searchsorted(xs, grid, side="right")] != 0
        return inside.ravel()

    wrong = []
    for name, svg in icons.items():
        centre = [cmd for path in centerlines(svg) for cmd in svg_commands(path)]
        dist = distance(*polylines(centre))
        outline = [cmd for path in outline_path(svg) for cmd in path.as_cmd_seq()]
        mismatch = (filled(*polylines(outline)) != (dist <= 1.0)) & (np.abs(dist - 1.0) > band)
        if mismatch.any():
            wrong.append(f"{name}: {int(mismatch.sum())} of {len(pts)} samples differ")
    return wrong


def _bbox_x(paths) -> tuple[float, float]:
    boxes = [p.bounding_box() for p in paths]
    return min(b.x for b in boxes), max(b.x + b.w for b in boxes)


def glyph(paths, scale: str) -> tuple[str, float]:
    """Return (path data, advance) for one scale, origin at the left margin
    on the baseline (y up is negative), the 24-unit frame centred on the
    middle of the cap height like SF Symbols."""
    _, Affine2D = _picosvg()
    ratio = SCALE_RATIO[scale]
    factor = SCALE * ratio
    xmin, xmax = _bbox_x(paths)
    bearing = SIDE_BEARING * ratio
    transform = Affine2D(factor, 0, 0, factor, bearing - xmin * factor, -CAP_HEIGHT / 2.0 - 12 * factor)
    d = " ".join(p.apply_transform(transform).round_floats(3).d for p in paths)
    advance = round((xmax - xmin) * factor + 2 * bearing, 3)
    return d, advance


def _line(id_: str, x1, x2, y1, y2) -> str:
    return (
        f'  <line id="{id_}" style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;" '
        f'x1="{x1:g}" x2="{x2:g}" y1="{y1:g}" y2="{y2:g}"/>'
    )


def symbol_template(name: str, paths) -> str:
    guides: list[str] = []
    symbols: list[str] = []
    for scale in ("S", "M", "L"):
        base = BASELINE[scale]
        cap = round(base - CAP_HEIGHT, 3)
        guides.append(_line(f"Baseline-{scale}", 263, 3036, base, base))
        guides.append(_line(f"Capline-{scale}", 263, 3036, cap, cap))
    for scale in ("S", "M", "L"):
        base = BASELINE[scale]
        d, advance = glyph(paths, scale)
        top, bottom = base - 120, base + 40
        guides.append(_line(f"left-margin-Regular-{scale}", LEFT_MARGIN_X, LEFT_MARGIN_X, top, bottom))
        right = round(LEFT_MARGIN_X + advance, 3)
        guides.append(_line(f"right-margin-Regular-{scale}", right, right, top, bottom))
        symbols.append(
            f'  <g id="Regular-{scale}" transform="matrix(1 0 0 1 {LEFT_MARGIN_X:g} {base:g})">\n'
            f'   <path d="{d}"/>\n'
            f"  </g>"
        )
    guides_xml = "\n".join(guides)
    symbols_xml = "\n".join(symbols)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <!--glyph: "{name}", point size: 100.0, coolicons v4.1 by Kryston Schwarze (CC BY 4.0), generated by scripts/shellx/import_coolicons.py-->
 <g id="Notes">
  <rect height="2200" id="artboard" style="fill:white;opacity:1" width="3300" x="0" y="0"/>
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;font-weight:bold;" transform="matrix(1 0 0 1 263 322)">Weight/Scale Variations</text>
  <text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;text-anchor:end;" transform="matrix(1 0 0 1 3036 1933)">Template v.3.0</text>
 </g>
 <g id="Guides">
{guides_xml}
 </g>
 <g id="Symbols">
{symbols_xml}
 </g>
</svg>
"""


def write_catalog(icons: dict[str, bytes], out: Path) -> None:
    """Render every symbol first, then replace ``out`` in one go, so an
    interrupted or failing run never leaves a half-written catalog."""
    if out.suffix != ".xcassets":
        sys.exit(f"{out}: the output must be an .xcassets directory")
    templates = {name: symbol_template(name, outline_path(svg)) for name, svg in icons.items()}
    for name, (source, transformation) in DERIVED.items():
        if name in icons:
            sys.exit(f"derived symbol {name} would replace a coolicon")
        templates[name] = symbol_template(name, derived_path(icons[source], transformation))
    templates = dict(sorted(templates.items()))
    staging = out.with_name(out.name + ".staging")
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    (staging / "Contents.json").write_text(
        json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n", encoding="utf-8"
    )
    for name, template in templates.items():
        folder = staging / f"{name}.symbolset"
        folder.mkdir()
        (folder / f"{name}.svg").write_text(template, encoding="utf-8")
        contents = {
            "info": {"author": "xcode", "version": 1},
            "symbols": [{"filename": f"{name}.svg", "idiom": "universal"}],
        }
        (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n", encoding="utf-8")
    if out.exists():
        shutil.rmtree(out)
    staging.rename(out)
    (out.parent / "NOTICE").write_text(NOTICE, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, help="coolicons.v4.1.zip (the pinned release)")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output .xcassets directory")
    parser.add_argument(
        "--verify", action="store_true",
        help="before writing, check every outline against its exact stroke region (needs numpy; ~10 min)",
    )
    args = parser.parse_args(argv)
    check_tool_versions()
    icons = load_svgs(args.source)
    if args.verify:
        wrong = verify_outlines(icons)
        if wrong:
            sys.exit("outlines differ from their strokes:\n  " + "\n  ".join(wrong))
        print(f"verified {len(icons)} outlines against their strokes")
    write_catalog(icons, args.out)
    print(f"wrote {len(icons)} coolicons + {len(DERIVED)} derived symbolsets to {args.out} (+ NOTICE)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
