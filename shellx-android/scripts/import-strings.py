#!/usr/bin/env python3
"""Generate the Android strings.xml files from the iPhone string catalog.

Reads shellx-ios/ShellX/Localizable.xcstrings and writes
shellx-android/app/src/main/res/values/strings.xml and values-vi/strings.xml.

Rules:
- Name: the key without its argument signature, camelCase split, dots to underscores (RENAMES wins).
- Formats: only %@, %lld and %d (plain or positional) are supported; they become %n$s and %n$d.
  The (position, type) set must be equal in en and vi. A plural form may leave an argument out (one = "One
  workspace"), but the forms of a language together use the same set, with one type per position.
- Plurals: only the forms Android uses for the language are allowed (CLDR: en one/other, vi other); a zero
  form is never used for en or vi, so it needs an override.
- Escaping: backslash, &, <, >, ', ", newline, tab, and a leading @ or ?. Edge or double spaces are refused.
- Keys with shouldTranslate=false get translatable="false" and are left out of values-vi.
- Keys in scripts/strings-ios-only.txt are skipped; a listed key missing from the catalog is refused.
- A name defined in values/strings_android.xml replaces the generated one (and is left out of both files).
  Every translatable Android name needs a values-vi/strings_android.xml twin, and an override keeps the
  iPhone string's arguments.
- iPhone wording (iPhone, App Store, VoiceOver, ...) in a generated value is refused until an override exists.
- Any problem is printed to stderr, nothing is written and the exit code is 1.
Use --check to compare instead of writing.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

RENAMES = {"agent.state.running %@": "agent_state_running_for"}
CLDR = ["zero", "one", "two", "few", "many", "other"]
# The plural forms Android picks from for each language (CLDR cardinal rules); any other form is never shown.
ANDROID_QUANTITIES = {"en": {"one", "other"}, "vi": {"other"}}
IOS_WORDING = re.compile(r"\b(?:iPhone|iPad|iOS|App Store|TestFlight|Apple|VoiceOver|Face ID|Touch ID|Keychain|iCloud|Siri)\b")
WORDING_HELP = ("add an Android override in strings_android.xml (values and values-vi) "
                "or list the key in shellx-android/scripts/strings-ios-only.txt")
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by shellx-android/scripts/import-strings.py from "
          "shellx-ios/ShellX/Localizable.xcstrings. Do not edit: run the script. -->\n")
CATALOG = "shellx-ios/ShellX/Localizable.xcstrings"
RES = "shellx-android/app/src/main/res"
FORMAT = re.compile(r"%(?:(\d+)\$)?(@|lld|d)")
ANDROID_ARG = re.compile(r"%(\d+)\$([sd])")


class Problems:
    def __init__(self) -> None:
        self.items = []

    def add(self, who: str, text: str) -> None:
        self.items.append("import-strings: %s: %s" % (who, text))


def android_name(key: str) -> str:
    if key in RENAMES:
        return RENAMES[key]
    segments = []
    for segment in key.split(" ", 1)[0].split("."):
        segment = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", segment)
        segment = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", segment)
        segments.append(segment.lower())
    return "_".join(segments)


def convert(value: str):
    """Return (android format text, set of (position, type)) or raise ValueError."""
    out = []
    args = set()
    plain = 0
    positional = 0
    i = 0
    while i < len(value):
        ch = value[i]
        if ch != "%":
            out.append(ch)
            i += 1
            continue
        m = FORMAT.match(value, i)
        if not m:
            raise ValueError("unsupported format near %r" % value[i:i + 6])
        if m.group(1):
            positional += 1
            pos = int(m.group(1))
        else:
            plain += 1
            pos = plain
        if plain and positional:
            raise ValueError("mixes plain and positional formats")
        kind = "s" if m.group(2) == "@" else "d"
        args.add((pos, kind))
        out.append("%%%d$%s" % (pos, kind))
        i = m.end()
    return "".join(out), args


def escape(text: str) -> str:
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def prepare(who: str, value: str, problems: Problems):
    """Convert and escape one value; returns (escaped, args) or None after reporting."""
    if not value:
        problems.add(who, "empty value")
        return None
    if value != value.strip() or "  " in value:
        problems.add(who, "leading, trailing or double spaces would be collapsed by Android: %r" % value)
        return None
    try:
        converted, args = convert(value)
    except ValueError as error:
        problems.add(who, "%s in %r" % (error, value))
        return None
    return escape(converted), args


def read_android(path: Path, problems: Problems):
    """Return {name: ('string'|'plurals', [raw texts], translatable)}."""
    result = {}
    if not path.is_file():
        return result
    try:
        root = ET.parse(str(path)).getroot()
    except ET.ParseError as error:
        problems.add(str(path), "not valid XML: %s" % error)
        return result
    for node in root:
        name = node.get("name")
        translatable = node.get("translatable") != "false"
        if node.tag == "string":
            result[name] = ("string", [node.text or ""], translatable)
        elif node.tag == "plurals":
            result[name] = ("plurals", [item.text or "" for item in node.findall("item")], translatable)
    return result


def android_args(texts):
    return [set((int(p), t) for p, t in ANDROID_ARG.findall(text)) for text in texts]


def build(root: Path, problems: Problems):
    catalog = json.loads((root / CATALOG).read_text(encoding="utf-8"))["strings"]
    ios_only_path = root / "shellx-android/scripts/strings-ios-only.txt"
    ios_only = []
    if ios_only_path.is_file():
        for line in ios_only_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                ios_only.append(line)
    for key in ios_only:
        if key not in catalog:
            problems.add(key, "listed in strings-ios-only.txt but missing from the catalog")
    skipped = set(ios_only)

    res = root / RES
    over_en = read_android(res / "values/strings_android.xml", problems)
    over_vi = read_android(res / "values-vi/strings_android.xml", problems)
    for name, (_, _, translatable) in over_en.items():
        if translatable and name not in over_vi:
            problems.add(name, "in values/strings_android.xml but missing from values-vi/strings_android.xml")
    for name in over_vi:
        if name not in over_en:
            problems.add(name, "in values-vi/strings_android.xml but missing from values/strings_android.xml")

    strings = {"values": {}, "values-vi": {}}
    plurals = {"values": {}, "values-vi": {}}
    names = {}
    for key in sorted(catalog):
        if key in skipped:
            continue
        entry = catalog[key]
        name = android_name(key)
        if not re.match(r"^[a-z][a-z0-9_]*$", name):
            problems.add(key, "name %r is not a valid Android resource name" % name)
            continue
        if name in names:
            problems.add(key, "name %s collides with %s; add a RENAMES entry" % (name, names[name]))
            continue
        names[name] = key
        translate = entry.get("shouldTranslate") is not False
        locs = entry.get("localizations", {})
        langs = [("values", "en")] + ([("values-vi", "vi")] if translate else [])
        overridden = name in over_en
        arg_sets = []
        pending = []
        for folder, lang in langs:
            loc = locs.get(lang)
            if loc is None:
                problems.add(key, "no %s translation" % lang)
                continue
            if "stringUnit" in loc:
                forms = [(None, loc["stringUnit"].get("value", ""))]
                kind = "string"
            elif set(loc.get("variations", {})) == {"plural"}:
                forms = [(q, loc["variations"]["plural"][q]["stringUnit"].get("value", ""))
                         for q in CLDR if q in loc["variations"]["plural"]]
                kind = "plurals"
                if not any(q == "other" for q, _ in forms):
                    problems.add(key, "%s plural has no 'other' form" % lang)
                    continue
                unused = [q for q, _ in forms if q not in ANDROID_QUANTITIES[lang]]
                if unused and not overridden:
                    problems.add(key, "%s plural form %s is never used by Android for this language (it uses %s); "
                                      "override the name in strings_android.xml (values and values-vi)"
                                 % (lang, ", ".join(unused), ", ".join(sorted(ANDROID_QUANTITIES[lang]))))
                    continue
            else:
                problems.add(key, "%s uses a variation Android cannot take (only plural is supported)" % lang)
                continue
            done = []
            for quantity, value in forms:
                if not overridden and IOS_WORDING.search(value):
                    problems.add(key, "iPhone wording in %r; %s" % (value, WORDING_HELP))
                    done = None
                    break
                prepared = prepare(key, value, problems)
                if prepared is None:
                    done = None
                    break
                done.append((quantity, prepared[0], prepared[1]))
            if done is None:
                continue
            used = set()
            for _, _, args in done:
                used |= args
            if len(set(pos for pos, _ in used)) != len(used):
                problems.add(key, "%s uses one argument position with two types" % lang)
                continue
            arg_sets.append(used)
            pending.append((folder, kind, [(q, t) for q, t, _ in done]))
        if arg_sets and any(a != arg_sets[0] for a in arg_sets):
            problems.add(key, "format arguments differ between languages")
            continue
        if overridden:
            expected = arg_sets[0] if arg_sets else None
            for label, table in (("values", over_en), ("values-vi", over_vi)):
                if name in table and expected is not None:
                    found = android_args(table[name][1])
                    if table[name][0] == "plurals":
                        found = [set().union(*found)] if found else [set()]
                    if any(f != expected for f in found):
                        problems.add(name, "override in %s/strings_android.xml keeps different arguments "
                                     "than the iPhone string %r" % (label, key))
            continue
        for folder, kind, items in pending:
            if kind == "string":
                strings[folder][name] = (items[0][1], not translate)
            else:
                plurals[folder][name] = items
    return strings, plurals


def render(strings, plurals) -> str:
    lines = [HEADER.rstrip("\n"), "<resources>"]
    for name in sorted(strings):
        text, untranslatable = strings[name]
        attr = ' translatable="false"' if untranslatable else ""
        lines.append('    <string name="%s"%s>%s</string>' % (name, attr, text))
    for name in sorted(plurals):
        lines.append('    <plurals name="%s">' % name)
        for quantity, text in plurals[name]:
            lines.append('        <item quantity="%s">%s</item>' % (quantity, text))
        lines.append("    </plurals>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main() -> int:
    default_root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description="Generate Android strings from the iPhone catalog.")
    parser.add_argument("--root", default=str(default_root), help="repository root")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    root = Path(args.root)
    problems = Problems()
    strings, plurals = build(root, problems)
    if problems.items:
        sys.stderr.write("\n".join(problems.items) + "\n")
        return 1
    outputs = {}
    for folder in ("values", "values-vi"):
        outputs[root / RES / folder / "strings.xml"] = render(strings[folder], plurals[folder])
    counts = "%d strings, %d plurals" % (len(strings["values"]), len(plurals["values"]))
    if args.check:
        stale = []
        for path, text in outputs.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        if stale:
            for path in stale:
                sys.stderr.write("import-strings: stale %s; run shellx-android/scripts/import-strings.py\n"
                                 % path.relative_to(root))
            return 1
        print("import-strings: ok (%s)" % counts)
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print("import-strings: wrote shellx-android/app/src/main/res/values/strings.xml and "
          "values-vi/strings.xml (%s)" % counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
