import type { Context } from "hono";
import type { AppEnv } from "../app.js";
import type { AuthContext } from "../auth/session.js";
import { authenticate } from "../auth/session.js";
import { parseBearer } from "../auth/tokens.js";
import { CONN_ID_HEADER, DEVICE_ID_HEADER, DEVICE_KIND_HEADER, hubFor } from "../hub/user-hub.js";
import { Errors } from "../http/errors.js";
import { logMeta } from "../log.js";
import { CloseCode } from "../protocol/frames.js";

/**
 * The only client headers forwarded to the Durable Object: what the WebSocket upgrade itself
 * needs. Everything else the client sent (Authorization in particular) is dropped rather than
 * allowlisted-out, so a hostile client cannot smuggle anything through the hub's own headers
 * (e.g. spoofing X-Shellx-Device-Id/-Kind, which are instead set below from the validated token).
 */
const UPGRADE_HEADERS = [
  "Upgrade",
  "Connection",
  "Sec-WebSocket-Key",
  "Sec-WebSocket-Version",
  "Sec-WebSocket-Protocol",
  "Sec-WebSocket-Extensions",
] as const;

/**
 * Builds the headers forwarded to the account's UserHub: only `UPGRADE_HEADERS` from the client
 * (whatever it sent for anything else — Cookie, X-Forwarded-For, its own X-Shellx-* headers, in
 * any letter case — is ignored, never copied), plus the two X-Shellx-* identity headers set from
 * the already-validated token, plus a random per-upgrade connection id generated by the Worker
 * (never the client's, even if it sent its own `X-Shellx-Conn-Id`). Exported so the allowlist
 * itself can be unit-tested directly.
 */
export function buildHubHeaders(
  clientHeaders: Headers,
  auth: Pick<AuthContext, "deviceId" | "kind">,
  connId: string,
): Headers {
  const headers = new Headers();
  for (const name of UPGRADE_HEADERS) {
    const value = clientHeaders.get(name);
    if (value !== null) headers.set(name, value);
  }
  headers.set(DEVICE_ID_HEADER, auth.deviceId);
  headers.set(DEVICE_KIND_HEADER, auth.kind);
  headers.set(CONN_ID_HEADER, connId);
  return headers;
}

/**
 * GET /v1/ws — validates the bearer token, then hands the upgrade to the account's UserHub.
 * A missing/revoked/expired token is refused with plain HTTP 401 `unauthorized` before any
 * upgrade happens (shellx_core maps that to the `revoked` state).
 */
export async function webSocketRoute(c: Context<AppEnv>): Promise<Response> {
  if (c.req.header("Upgrade")?.toLowerCase() !== "websocket") throw Errors.upgradeRequired();
  const token = parseBearer(c.req.header("Authorization"));
  const auth = await authenticate(c.env.DB, token, c.get("now")());
  if (auth === null) throw Errors.unauthorized();

  const connId = crypto.randomUUID();
  const headers = buildHubHeaders(c.req.raw.headers, auth, connId);
  const hub = hubFor(c.env, auth.userId);
  const response = await hub.fetch(new Request("https://user-hub/connect", { headers }));
  if (response.status === 101) {
    // TOCTOU guard (fix rounds 1-2): a revocation (password change, account deletion) can commit to
    // D1 — and run its own hub.disconnect()/closeAccount() — in the gap between the authenticate()
    // above and this upgrade actually landing in the hub. If that revocation's own close ran before
    // this socket existed there to be closed by it, the device would otherwise stay connected
    // indefinitely (the runtime auto-answers "ping" without waking the object, so a dead-but-revoked
    // socket never times out on its own) — exactly what "change your password to sign out a lost
    // phone" is supposed to prevent. Re-validate the same token now that the socket is live.
    //
    // Once hub.fetch() returned 101, ALWAYS return that response (fix round 2): the socket already
    // exists in the hub — accepted, announced online, its queue delivered — so letting any failure
    // from here on propagate would discard a perfectly good upgrade in favour of an HTTP 500 while
    // leaving a phantom live device behind (the real client, meanwhile, never even sees the socket).
    // Fail closed instead: treat a re-check that couldn't complete (e.g. a D1 outage) the same as
    // "revoked", log metadata only, and best-effort close just this connection — never the response.
    //
    // "Just this connection", not "whatever this device has": closeConnection(connId, ...) targets
    // the exact socket this upgrade just created, unlike disconnect([deviceId], ...), which would
    // instead close a *different*, legitimate socket if this same device reconnected with a fresh,
    // valid token before this stale request's re-check got here (see UserHub.closeConnection).
    try {
      const stillValid = (await authenticate(c.env.DB, token, c.get("now")())) !== null;
      if (!stillValid) await hub.closeConnection(connId, CloseCode.revoked);
    } catch {
      logMeta("ws_recheck_failed", { device_id: auth.deviceId });
      // Best-effort retry, itself guarded: an RPC that throws synchronously (never even returning a
      // promise) would otherwise skip a chained `.catch()` and still escape this function.
      try {
        await hub.closeConnection(connId, CloseCode.revoked);
      } catch {
        // Nothing more we can do without risking discarding the already-issued 101 response.
      }
    }
  }
  return response;
}
