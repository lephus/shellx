final Map<int, int> _compose = _build();
final Map<int, (int, int)> _decompose = {};

Map<int, int> _build() {
  final m = <int, int>{};
  for (var i = 0; i + 12 <= _table.length; i += 12) {
    final a = int.parse(_table.substring(i, i + 4), radix: 16);
    final b = int.parse(_table.substring(i + 4, i + 8), radix: 16);
    final c = int.parse(_table.substring(i + 8, i + 12), radix: 16);
    m[(a << 16) | b] = c;
    _decompose[c] = (a, b);
  }
  return m;
}

/// [base] followed by [mark] as one code point, or null when there is none.
/// A mark that canonically sorts before the one already on [base] goes
/// underneath it ("e" + U+0302 on a dot-below "ẹ" gives "ệ").
int? composePair(int base, int mark) {
  final direct = _compose[(base << 16) | mark];
  if (direct != null) return direct;
  final parts = _decompose[base];
  if (parts == null || _ccc(mark) >= _ccc(parts.$2)) return null;
  final inner = _compose[(parts.$1 << 16) | mark];
  return inner == null ? null : _compose[(inner << 16) | parts.$2];
}

/// [s] with every base letter and its marks composed.
String composeLatin(String s) {
  var any = false;
  for (var i = 0; i < s.length; i++) {
    if (isCombiningMark(s.codeUnitAt(i))) {
      any = true;
      break;
    }
  }
  if (!any) return s;
  final out = <int>[];
  for (var i = 0; i < s.length; i++) {
    final c = s.codeUnitAt(i);
    if (isCombiningMark(c) && out.isNotEmpty) {
      final merged = composePair(out.last, c);
      if (merged != null) {
        out[out.length - 1] = merged;
        continue;
      }
    }
    out.add(c);
  }
  return String.fromCharCodes(out);
}
