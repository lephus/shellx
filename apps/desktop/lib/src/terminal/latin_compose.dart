/// Canonical composition for the Latin letters (Vietnamese included), so a
/// search finds "é" whether the terminal holds U+00E9 or "e" + U+0301, and
/// whichever the user typed (A10 D3). Dart has no Unicode normalisation of
/// its own; this covers U+00C0-U+024F and U+1E00-U+1EFF, enough for
/// Western European and Vietnamese text. Other scripts compare as stored.
library;

/// Combining diacritical marks block.
bool isCombiningMark(int c) => c >= 0x300 && c <= 0x36F;

/// Combining class of the marks that matter here: the horn U+031B is 216,
/// the dot and ring below 220-ish, the rest above (230).
int _ccc(int mark) => switch (mark) {
  0x31B => 216,
  0x323 ||
  0x324 ||
  0x325 ||
  0x326 ||
  0x327 ||
  0x328 ||
  0x32D ||
  0x32E ||
  0x330 ||
  0x331 => 220,
  _ => 230,
};

